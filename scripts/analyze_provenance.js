const fs = require('fs');
const path = require('path');
if (typeof process.loadEnvFile === 'function') process.loadEnvFile(path.join(__dirname, '..', '.env'));
const { Pool } = require('pg');

const pool = new Pool({
    connectionString: process.env.DATABASE_URL,
    ssl: { rejectUnauthorized: false }
});

async function analyzeProvenance() {
    try {
        const localStudents = JSON.parse(fs.readFileSync(path.join(__dirname, '..', '.data', 'students.json'), 'utf8'));
        console.log(`Local students count: ${localStudents.length}`);

        const dbRes = await pool.query(`
            SELECT s.id as student_id, s.roll_number, s.department, s.created_at,
                   p.id as profile_id, p.firebase_uid, p.email, p.full_name
            FROM students s
            LEFT JOIN profiles p ON s.profile_id = p.id
        `);
        console.log(`DB students count: ${dbRes.rows.length}`);

        // Define clear patterns for Antigravity-created test/demo data:
        // 1. Roll starts with '22LOAD', '22U120', '22LIVE', '22ACT', '22DEL', 'TEST', 'STUDENT999'
        // 2. Name contains 'Load Candidate', 'Test Student', 'Candidate For Deletion', 'Live Verification Student', 'Candidate 22'
        // 3. Email ends with '@kits.edu' AND roll was auto-generated test roll
        // 4. Default demo students in server.js: 22IT001, 22IT002, 22IT003, 22CSE014 (A. Srikanth, B. Manasa, C. Venkat Rao, D. Harish)

        function isAntigravityTestData(s) {
            const roll = (s.roll_number || '').toUpperCase().trim();
            const name = (s.name || s.full_name || '').toLowerCase().trim();
            const email = (s.email || '').toLowerCase().trim();
            const fuid = (s.firebase_uid || '').toLowerCase().trim();

            if (roll.startsWith('22LOAD') || roll.startsWith('22U120') || roll.startsWith('22LIVE') ||
                roll.startsWith('22ACT') || roll.startsWith('22DEL') || roll.startsWith('TEST') ||
                roll.startsWith('STUDENT999') || roll.includes('DUMMY') || roll.startsWith('LOAD')) {
                return { isTest: true, reason: 'Prefix/Pattern matched test roll' };
            }

            if (name.includes('load candidate') || name.includes('test student') || 
                name.includes('candidate for deletion') || name.includes('live verification student') ||
                name.includes('candidate 22') || name.includes('dummy')) {
                return { isTest: true, reason: 'Test name pattern' };
            }

            if (fuid.startsWith('uid_17') || fuid.includes('dummy') || fuid.startsWith('admin_created_22del')) {
                return { isTest: true, reason: 'Synthetic UID generated by test script' };
            }

            // Check if default demo student from DEFAULT_STUDENTS
            if (['22IT001', '22IT002', '22IT003', '22CSE014'].includes(roll)) {
                return { isTest: true, reason: 'Antigravity default seed student' };
            }

            return { isTest: false };
        }

        console.log('\n=== REAL / INSTITUTIONAL STUDENTS IN DB ===');
        const dbGenuine = [];
        const dbTest = [];
        dbRes.rows.forEach(r => {
            const check = isAntigravityTestData(r);
            if (check.isTest) {
                dbTest.push({ ...r, reason: check.reason });
            } else {
                dbGenuine.push(r);
            }
        });

        console.log(`DB Test records: ${dbTest.length}`);
        console.log(`DB Genuine records: ${dbGenuine.length}`);
        console.table(dbGenuine.map(r => ({
            roll: r.roll_number,
            name: r.full_name,
            email: r.email,
            fuid: r.firebase_uid,
            created_at: r.created_at
        })));

        console.log('\n=== REAL / INSTITUTIONAL STUDENTS IN LOCAL DATA ===');
        const localGenuine = [];
        const localTest = [];
        localStudents.forEach(r => {
            const check = isAntigravityTestData(r);
            if (check.isTest) {
                localTest.push({ ...r, reason: check.reason });
            } else {
                localGenuine.push(r);
            }
        });

        console.log(`Local Test records: ${localTest.length}`);
        console.log(`Local Genuine records: ${localGenuine.length}`);
        console.table(localGenuine.map(r => ({
            roll: r.roll_number,
            name: r.name,
            email: r.email,
            created_at: r.created_at
        })));

    } catch (e) {
        console.error('Error during provenance analysis:', e);
    } finally {
        await pool.end();
    }
}

analyzeProvenance();
